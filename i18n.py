def get_strings(lang):
    """UI strings for a language code; falls back to English."""
    if lang in UI_STRINGS:
        return UI_STRINGS[lang]
    return UI_STRINGS["en"]


def is_verified(lang):
    """True when the language has hand-written UI strings + golden content."""
    return lang in UI_STRINGS


def native_name(lang):
    if lang == "en":
        return "English"
    if lang in UI_STRINGS:
        # native names live in the language picker template context
        return {"es": "Español", "hi": "हिन्दी", "pa": "ਪੰਜਾਬੀ",
                "zh": "中文", "fa": "فارسی"}[lang]
    return EXTRA_LANGUAGES.get(lang, (lang, lang))[0]
